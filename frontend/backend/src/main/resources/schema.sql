CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS auth_tokens (
    token VARCHAR(36) PRIMARY KEY,
    user_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_auth_tokens_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS assessments (
    id VARCHAR(40) PRIMARY KEY,
    user_id BIGINT,
    device_type VARCHAR(40) NOT NULL,
    powers_on VARCHAR(20) NOT NULL,
    device_condition VARCHAR(40) NOT NULL,
    physical_damage VARCHAR(40) NOT NULL,
    preference VARCHAR(20) NOT NULL,
    recommendation VARCHAR(20) NOT NULL,
    reason VARCHAR(500) NOT NULL,
    estimated_value_min DOUBLE PRECISION NOT NULL,
    estimated_value_max DOUBLE PRECISION NOT NULL,
    value_type VARCHAR(100) NOT NULL,
    estimated_weight_kg DOUBLE PRECISION NOT NULL,
    waste_diverted_kg DOUBLE PRECISION NOT NULL,
    co2_saved_kg DOUBLE PRECISION NOT NULL,
    recoverable_materials VARCHAR(2000) NOT NULL,
    image_data BLOB,
    image_content_type VARCHAR(100),
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_assessments_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS pickups (
    id VARCHAR(40) PRIMARY KEY,
    reference VARCHAR(40) NOT NULL UNIQUE,
    user_id BIGINT,
    analysis_id VARCHAR(40),
    full_name VARCHAR(80) NOT NULL,
    phone VARCHAR(20) NOT NULL,
    address VARCHAR(500) NOT NULL,
    city VARCHAR(120) NOT NULL,
    state VARCHAR(120) NOT NULL,
    pin_code VARCHAR(10) NOT NULL,
    pickup_date VARCHAR(10) NOT NULL,
    time_slot VARCHAR(30) NOT NULL,
    instructions VARCHAR(1000),
    device_type VARCHAR(40) NOT NULL,
    status VARCHAR(30) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_pickups_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_pickups_assessment FOREIGN KEY (analysis_id) REFERENCES assessments(id)
);

CREATE INDEX IF NOT EXISTS idx_assessments_user_created
    ON assessments(user_id, created_at);
CREATE INDEX IF NOT EXISTS idx_pickups_user_created
    ON pickups(user_id, created_at);
